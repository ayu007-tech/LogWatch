import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.time.LocalDateTime;

public class ReportGenerator {

    private final String reportDirectory;

    public ReportGenerator(String reportDirectory) {
        this.reportDirectory = reportDirectory;
    }


    // =========================================================
    // GENERATE REPORT
    // =========================================================

    public void generateReport(
            LogStatistics statistics,
            HealthAnalyzer healthAnalyzer) {

        try {

            // Create reports directory if it doesn't exist
            File directory =
                    new File(reportDirectory);

            if (!directory.exists()) {

                directory.mkdirs();
            }


            // Report file
            File reportFile =
                    new File(
                            directory,
                            "logwatch-report.txt"
                    );


            FileWriter writer =
                    new FileWriter(reportFile);


            // =================================================
            // REPORT HEADER
            // =================================================

            writer.write(
                    "========================================\n"
            );

            writer.write(
                    "             LOGWATCH REPORT\n"
            );

            writer.write(
                    "========================================\n\n"
            );


            writer.write(
                    "Generated At: "
                            + LocalDateTime.now()
                            + "\n\n"
            );


            // =================================================
            // STATISTICS
            // =================================================

            writer.write(
                    "========== LOG STATISTICS ==========\n\n"
            );


            int totalLogs =
                    statistics.getTotalLogs();

            int info =
                    statistics.getCount("INFO");

            int warning =
                    statistics.getCount("WARNING");

            int error =
                    statistics.getCount("ERROR");

            int exception =
                    statistics.getCount("EXCEPTION");


            writer.write(
                    "Total Logs      : "
                            + totalLogs
                            + "\n"
            );

            writer.write(
                    "INFO            : "
                            + info
                            + "\n"
            );

            writer.write(
                    "WARNING         : "
                            + warning
                            + "\n"
            );

            writer.write(
                    "ERROR           : "
                            + error
                            + "\n"
            );

            writer.write(
                    "EXCEPTION       : "
                            + exception
                            + "\n\n"
            );


            // =================================================
            // HEALTH SCORE
            // =================================================

            writer.write(
                    "========== SYSTEM HEALTH ==========\n\n"
            );


            int penalty =
                    (error * 10)
                    + (exception * 15)
                    + (warning * 3);


            int healthScore =
                    100 - penalty;


            if (healthScore < 0) {
                healthScore = 0;
            }


            String status;


            if (healthScore >= 80) {

                status = "HEALTHY";

            } else if (healthScore >= 50) {

                status = "WARNING";

            } else {

                status = "CRITICAL";
            }


            writer.write(
                    "Health Score    : "
                            + healthScore
                            + " / 100\n"
            );

            writer.write(
                    "System Status   : "
                            + status
                            + "\n\n"
            );


            // =================================================
            // FOOTER
            // =================================================

            writer.write(
                    "========================================\n"
            );

            writer.write(
                    "          Generated by LogWatch\n"
            );

            writer.write(
                    "========================================\n"
            );


            writer.close();


            System.out.println();

            System.out.println(
                    "Report generated successfully!"
            );

            System.out.println(
                    "Location: "
                            + reportFile.getAbsolutePath()
            );


        } catch (IOException e) {

            System.out.println(
                    "Error generating report: "
                            + e.getMessage()
            );
        }
    }
}